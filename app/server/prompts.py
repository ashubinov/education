"""Промпты для генерации курса. Все задачи возвращают один JSON-объект.

Принципы, заложенные во всех промптах:
  * опора только на загруженные материалы (никаких выдуманных фактов);
  * «лестница»: от простого к сложному, термины вводятся до того, как на них опираются вопросы;
  * микро-уроки по 3–5 минут;
  * качественные дистракторы (правдоподобные типичные ошибки);
  * адаптация: в каждый запрос передаётся профиль ученика (слабые/сильные понятия, заметки прошлых модулей);
  * правильные и неправильные варианты возвращаются отдельно (перемешиваем на сервере → нет «любимой» позиции ответа).
"""

LANG_NAMES = {"ru": "русском", "en": "английском"}

SYSTEM = """Ты — опытный методист и преподаватель. Ты строишь пошаговый курс обучения СТРОГО по материалам, которые загрузил пользователь, и ведёшь ученика от начала до конца небольшими шагами.

ЖЁСТКИЕ ПРАВИЛА
1. Источник истины — только «МАТЕРИАЛЫ». Не выдумывай факты, цифры, определения и имена. Если для понимания нужно короткое пояснение, которого нет в материалах, оно должно быть общеизвестным и не противоречить материалам.
2. Язык всего курса — {lang}. Термины на другом языке оставляй как в материалах (при необходимости с переводом в скобках).
3. Логика «лестницы»: от простого к сложному; каждое новое понятие опирается на уже введённые. Не требуй от ученика знаний, которых ещё не было в курсе.
4. Вопросы должны быть самодостаточными: не пиши «в тексте», «в лекции», «на слайде», «согласно материалу», не цитируй служебные метки вида [#3] (это только номера фрагментов для ссылок в JSON). Не задавай вопросов про даты занятий, оформление, служебные пометки конспекта, номера слайдов.
5. Качество вопросов: проверяй понимание, а не угадывание. Неверные варианты правдоподобны (типичные ошибки и путаницы), примерно одинаковой длины и стиля с верным; никаких «все перечисленное», «ничего из перечисленного», «оба варианта».
6. Объяснение (explanation) — 1–2 коротких предложения: почему верный вариант верен и в чём ловушка. Оно показывается ученику после ответа и должно учить.
7. Формулы и код пиши обычным текстом (например, tf(w,d) = n(w,d) / n(d)); многострочный код — в одной строке JSON с символами \\n. Внутри JSON-строк вместо двойных кавычек используй «ёлочки» или одинарные кавычки.
8. Ответ — РОВНО ОДИН валидный JSON-объект. Без markdown, без ```-блоков, без комментариев и текста до/после.
9. Учитывай ПРОФИЛЬ УЧЕНИКА, если он дан: слабые понятия объясняй и проверяй подробнее и с новых сторон, сильные — не пережёвывай; подстраивай сложность под успеваемость."""


def system(lang: str) -> str:
    return SYSTEM.format(lang=LANG_NAMES.get(lang, "языке материалов"))


# ---------------------------------------------------------------- вопросы (общая часть)
QUESTION_SPEC = """ФОРМАТ ВОПРОСОВ (поле "questions" — массив объектов; kind бывает только таким):
 1) {"kind":"single","concept":"<термин/понятие, которое проверяется>","prompt":"<вопрос>","correct":"<один верный ответ>","wrong":["<неверный>","<неверный>","<неверный>"],"explanation":"..."}
 2) {"kind":"multi","concept":"...","prompt":"<вопрос; в конце «(выберите все верные)»>","correct":["<верный>","<верный>"],"wrong":["<неверный>","<неверный>"],"explanation":"..."}   (верных 2–3, неверных 2–3)
 3) {"kind":"fill","concept":"<искомый термин>","prompt":"<предложение или определение с пропуском ___ на месте термина/значения>","accept":["<основной ответ>","<синоним/вариант написания>"],"explanation":"..."}   (ответ — одно слово или короткая фраза; перечисли допустимые варианты написания, в т.ч. сокращения и перевод)
 4) {"kind":"image","concept":"...","svg":"<svg ...>...</svg>","prompt":"<вопрос по картинке>","correct":"<верный>","wrong":["..","..","<неверный>"],"explanation":"..."}
ПРАВИЛА ДЛЯ kind=image: SVG — простая схема, поясняющая понятие (дерево разбора, график, цепочка этапов, вектор на плоскости, структура данных, сравнение величин и т.п.). Атрибуты SVG только в одинарных кавычках. Обязательно: viewBox='0 0 400 240', xmlns='http://www.w3.org/2000/svg', подписи на языке курса (font-size 14–16, fill='#222'), на светлом фоне: первым элементом <rect width='400' height='240' fill='#f7f7fb' rx='12'/>. Только базовые фигуры (rect, circle, line, path, polygon, text), не более ~2500 символов, без скриптов, внешних ссылок и изображений. Вопрос должен ТРЕБОВАТЬ чтения картинки (нельзя ответить, не глядя на неё). Если тема не визуализируется — не используй image."""


def _profile_block(profile: str) -> str:
    return f"\nПРОФИЛЬ УЧЕНИКА (учитывай при составлении):\n{profile}\n" if profile else ""


# ---------------------------------------------------------------- 1. дайджест фрагментов (для больших материалов)
def digest(chunks: list[tuple[int, str]]) -> str:
    body = "\n\n".join(f"[#{i}]\n{t}" for i, t in chunks)
    return f"""Ниже фрагменты материалов. Для КАЖДОГО фрагмента сделай сжатый конспект, по которому можно спланировать курс.

{body}

Верни JSON:
{{"digests":[{{"id":<номер фрагмента без #>,"summary":"<2–3 предложения: о чём фрагмент>","terms":["<ключевые термины фрагмента, 3–8 штук>"],"practice":<true, если во фрагменте есть задачи/код/расчёты/упражнения, иначе false>}}]}}"""


# ---------------------------------------------------------------- 2. структура курса
def outline(material: str, filenames: list[str], user_title: str, full: bool) -> str:
    kind = "полный текст, разбитый на фрагменты [#N]" if full else "сжатые конспекты фрагментов [#N]"
    return f"""Составь структуру курса по МАТЕРИАЛАМ ({kind}). Файлы: {", ".join(filenames)}.
{"Желаемое название курса от пользователя: " + user_title if user_title else "Придумай короткое ёмкое название курса."}

МАТЕРИАЛЫ:
{material}

ТРЕБОВАНИЯ К СТРУКТУРЕ
- Модулей от 3 до 9 в зависимости от объёма (на ~5–8 страниц текста — примерно один модуль). Модуль = одна связная тема, которую можно освоить за 20–40 минут.
- Порядок — логика обучения: сначала базовые понятия и обозначения, затем то, что на них опирается. Без дублирования модулей.
- Весь существенный материал должен попасть хотя бы в один модуль. Каждый модуль ссылается на фрагменты-источники (chunk_ids).
- Служебные части (введение, «как читать», оглавление, список литературы) не делай отдельными модулями.
- has_practice = true, только если в материалах есть задачи, расчёты, код или алгоритмы, которые ученик может выполнять руками. practice_kind: "code" (написание кода), "problems" (расчётные/логические задачи), либо "none".
- practical модуля = true, если к его теме можно дать практическое задание на 5 минут.
- estimated_terms — сколько важных терминов/понятий в модуле (целое 3–12).

Верни JSON:
{{"title":"...","description":"<1–2 предложения: чему научится ученик>","icon":"<один подходящий эмодзи>","has_practice":false,"practice_kind":"none",
"modules":[{{"title":"...","summary":"<2–3 предложения о содержании>","objectives":["<что ученик сможет после модуля>","..."],"chunk_ids":[1,2],"practical":false,"estimated_terms":6}}]}}"""


# ---------------------------------------------------------------- 3. план модуля (термины)
def module_plan(course_title: str, module: dict, context: str, profile: str, done_terms: list[str]) -> str:
    return f"""Курс: «{course_title}». Спланируй модуль «{module['title']}».
Описание модуля: {module.get('summary','')}
Цели: {"; ".join(module.get('objectives') or [])}
{_profile_block(profile)}
Термины, которые ученик УЖЕ проходил в предыдущих модулях (не повторяй их как новые): {", ".join(done_terms[-40:]) or "—"}

МАТЕРИАЛЫ МОДУЛЯ:
{context}

Выдели термины/понятия, которые нужно изучить в этом модуле, в ПОРЯДКЕ изучения (от базовых к зависимым). Бери только то, что реально есть в материалах и важно для понимания: определения, названия методов/алгоритмов/объектов, формулы-понятия. От 3 до 9 терминов (чаще 6). Для каждого — короткая суть (gist), чтобы потом написать определение.
practice_tasks: 0, если в модуле нет материала для практики; иначе 1 (максимум 2 для больших практических модулей).{" Курс не предполагает практики — ставь 0." if not module.get('_course_practice') else ""}
focus: 1–2 предложения, на что сделать упор, с учётом профиля ученика.

Верни JSON:
{{"terms":[{{"term":"<название термина как в материалах>","gist":"<суть в 1 фразе>"}}],"practice_tasks":0,"focus":"..."}}"""


# ---------------------------------------------------------------- 4. входной тест
def intro_test(course_title: str, module: dict, terms: list[dict], context: str, profile: str, n: int = 8) -> str:
    tl = "\n".join(f"- {t['term']}: {t.get('gist','')}" for t in terms)
    return f"""Курс: «{course_title}». Составь ВХОДНОЙ ТЕСТ к модулю «{module['title']}». Он занимает у ученика около 3 минут.

Цель теста двойная: (а) выявить, где у ученика пробелы ДО изучения; (б) познакомить с терминами модуля — объяснение после каждого ответа (explanation) должно кратко вводить термин, даже если ответ неверный. Поэтому объяснения чуть подробнее обычных (1–3 предложения).

ТЕРМИНЫ МОДУЛЯ:
{tl}
{_profile_block(profile)}
МАТЕРИАЛЫ МОДУЛЯ:
{context}

Составь ровно {n} вопросов, по каждому ключевому термину модуля хотя бы один (если терминов больше {n} — выбери главные). Смесь типов: single (примерно 3–4), multi (1), fill — дополнение термина в определении (2–3), image — по картинке (1–2, ТОЛЬКО если тему можно показать схемой; иначе замени на single). Сложность растёт от лёгких к чуть более сложным; первый вопрос — самый простой, чтобы ученик «вошёл в ритм». Вопросы не должны требовать знаний, которых нет в материалах.

{QUESTION_SPEC}

Верни JSON: {{"questions":[...]}}"""


# ---------------------------------------------------------------- 5. урок «термины»
def terms_lesson(course_title: str, module: dict, terms: list[dict], context: str, profile: str,
                 other_terms: list[str]) -> str:
    tl = "\n".join(f"- {t['term']}: {t.get('gist','')}" for t in terms)
    return f"""Курс: «{course_title}», модуль «{module['title']}». Составь урок по написанию терминов для следующих терминов (их {len(terms)}):
{tl}
{_profile_block(profile)}
МАТЕРИАЛЫ МОДУЛЯ:
{context}

Для каждого термина дай:
- definition — определение 1–2 предложения (15–35 слов), самодостаточное, на основе материалов, без повторения самого термина в первых словах там, где можно обойтись; ученик будет сначала читать его, затем дописывать вторую половину, затем писать целиком — поэтому формулировка должна быть чёткой, запоминаемой, без вводных слов;
- key_points — 3–5 коротких ключевых слов/понятий (1–3 слова, в начальной форме), которые ОБЯЗАТЕЛЬНО должны прозвучать в верном определении (по ним проверяется ответ ученика);
- example — короткий пример или аналогия из жизни/из материалов (1 предложение);
- wrong_terms — 3 правдоподобных НЕверных термина-«двойника» (из той же области, чаще путаемые с этим; можно брать из списка уже известных: {", ".join(other_terms[:25]) or "—"});
- wrong_definitions — 3 правдоподобных НЕверных определения этого термина (того же размера и стиля, но с подменой существенного признака; они не должны быть верными определениями другого термина из списка выше).

Верни JSON:
{{"terms":[{{"term":"...","definition":"...","key_points":["..",".."],"example":"...","wrong_terms":["..","..",".."],"wrong_definitions":["..","..",".."]}}]}}"""


# ---------------------------------------------------------------- 6. практика
def practice(course_title: str, module: dict, kind: str, context: str, profile: str, terms: list[str],
             previous: list[str]) -> str:
    kind_txt = {"code": "задача на написание кода (короткая, решается за ~5 минут, 5–15 строк)",
                "problems": "расчётная или логическая задача (решается за ~5 минут, 3–6 шагов)"}.get(kind, "практическая задача (~5 минут)")
    return f"""Курс: «{course_title}», модуль «{module['title']}». Составь ОДНО практическое задание: {kind_txt}.
Изученные термины модуля: {", ".join(terms) or "—"}.
Уже были задания (не повторяй): {"; ".join(previous[-6:]) or "—"}.
{_profile_block(profile)}
МАТЕРИАЛЫ МОДУЛЯ:
{context}

Требования к заданию
- Должно решаться методами, которые даны в материалах курса; ученик не должен гуглить.
- Условие самодостаточное, с конкретными данными/примером ввода-вывода.
- starter — заготовка (для кода — шаблон функции с комментариями; для задач — пустая строка или данные).
- hints — 2–3 подсказки по нарастанию (не раскрывающие решение целиком).
- solution — эталонное решение с краткими пояснениями шагов.
- rubric — 3–5 критериев проверки (что должно быть в верном решении).
- methods — 3–5 методов/приёмов из курса, которые нужны для решения, каждый: name + when (когда применяют, 1 фраза).

После задания ученик пройдёт тест «какие методы применялись». Составь для него 5 вопросов (методы выбирай из methods, плюс типичные неверные альтернативы из курса): «какой приём применить в такой-то ситуации», «зачем нужен шаг…», «какой метод подойдёт для…» — в формате вопросов ниже (только kind single/multi/fill).

{QUESTION_SPEC}

Верни JSON:
{{"task":{{"title":"<короткое название>","kind":"{kind if kind in ('code','problems') else 'problems'}","language":"<язык программирования или пустая строка>","statement":"...","starter":"...","hints":["..",".."],"solution":"...","rubric":["..",".."],"methods":[{{"name":"..","when":".."}}]}},"questions":[...]}}"""


def evaluate_practice(task: dict, answer: str) -> str:
    return f"""Проверь решение ученика. Будь доброжелательным, но честным и конкретным.

ЗАДАНИЕ: {task.get('statement','')}
КРИТЕРИИ: {"; ".join(task.get('rubric') or [])}
ЭТАЛОН: {task.get('solution','')}

РЕШЕНИЕ УЧЕНИКА:
\"\"\"
{answer[:4000]}
\"\"\"

Оцени по критериям (частично верное решение — частичный балл). Решение, отличающееся от эталона, но корректное, считай верным. Не засчитывай пустые/бессмысленные ответы.
Верни JSON:
{{"score":<число от 0 до 1>,"verdict":"correct|partial|wrong","feedback":"<2–4 предложения: что хорошо, что неверно, как исправить>","missing":["<чего не хватило, по критериям>"],"concepts":["<понятия/методы курса, в которых ученик ошибся (может быть пусто)>"]}}"""


# ---------------------------------------------------------------- 7. контрольный тест
def final_test(course_title: str, module: dict, terms: list[str], context: str, profile: str,
               asked: list[str], weak: list[str], n: int = 8) -> str:
    return f"""Курс: «{course_title}». Составь КОНТРОЛЬНЫЙ ТЕСТ по модулю «{module['title']}» (итог модуля). Термины модуля: {", ".join(terms)}.
{_profile_block(profile)}
Слабые места ученика в этом модуле (сделай на них упор, спроси по-новому): {", ".join(weak) or "не выявлены — проверь равномерно"}.
Вопросы, которые уже задавались (НЕ повторяй, перефразируй и меняй ракурс): {" | ".join(a[:90] for a in asked[-14:]) or "—"}

МАТЕРИАЛЫ МОДУЛЯ:
{context}

Составь ровно {n} вопросов: проверка понимания и применения (не только заучивания). Смесь: single (3–4), multi (1–2), fill (2), image (0–1, только если уместно). Сложность — от средней к повышенной. Контрольный тест также включает задания на термины (их добавит система — не добавляй).

{QUESTION_SPEC}

Верни JSON: {{"questions":[...]}}"""


# ---------------------------------------------------------------- 8. анализ прогресса и адаптация
def adapt(course_title: str, summary: str, remaining: list[dict], notes: str) -> str:
    rem = "\n".join(f"{i}. {m['title']} — {m.get('summary','')}" for i, m in enumerate(remaining, 1)) or "— модулей не осталось"
    return f"""Курс: «{course_title}». Ученик завершил очередной модуль. Проанализируй, как он справляется, и скорректируй продолжение курса.

РЕЗУЛЬТАТЫ УЧЕНИКА:
{summary}

ПРЕДЫДУЩИЕ ЗАМЕТКИ О УЧЕНИКЕ: {notes or "—"}

ОСТАВШИЕСЯ МОДУЛИ:
{rem}

Сделай:
1. notes — обновлённые заметки об ученике (до 500 символов): что усвоено, где системные пробелы (по каким понятиям/типам заданий), какой темп и стиль подходят, что учитывать дальше (например, «чаще ошибается в формулах — давать больше примеров с числами»).
2. review — если есть сильные пробелы, которые помешают следующим темам, предложи ОДИН короткий модуль повторения: {{"title":"Повторение: ...","summary":"..."}}, иначе null. Он будет вставлен перед следующим модулем и построен только на уже изученных материалах.
3. message — короткая (1–2 предложения) тёплая обратная связь ученику с конкретикой, без лести.

Верни JSON:
{{"notes":"...","review":null,"message":"..."}}"""
