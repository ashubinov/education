def tier_unlocked(tier: int, selection: int) -> bool:
    return tier == 1 or (tier == 2 and selection >= 1) or (tier == 3 and selection >= 3)


def grow_time(species: str, lamps: int) -> int:
    return max(1, int(SPECIES[species]["grow"] * (1 - .08 * lamps)))


def cycle_time(species: str, drip: int) -> int:
    return max(1, int(SPECIES[species]["cycle"] * (1 - .07 * drip)))


def cone_cap(storage: int) -> int:
    return BASE_CONE_CAP + 2 * storage


def pots_count(level: int) -> int:
    return START_POTS + level


def price_bonus(appraiser: int, tiers_done: int) -> float:
    return .04 * appraiser + TIER_BONUS * tiers_done
