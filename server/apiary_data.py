"""Данные «Пасеки» (локация фермы): цветы, мёд, улучшения. Всё придумано для LearnQuest.

В каждом улье пчёлы собирают мёд по баночке за цикл, пока у них есть цветы: луговые травы бесплатны и бесконечны, а подсолнух, клубника и тыква берутся
со склада фермы (одна штука хватает на несколько циклов) и дают мёд дороже. Мёд копится в улье (до предела рамок) и ждёт, пока его заберут.
Для проверки время можно ускорить переменной окружения APIARY_SPEED (например, 120 — час превращается в полминуты).
"""
import os

from .loc_common import make_upgrades

try:
    SPEED = max(1.0, float(os.environ.get("APIARY_SPEED", "1")))
except ValueError:
    SPEED = 1.0

UNLOCK_FARM_LEVEL = 11
START_HIVES = 2
BASE_CAP = 4                 # баночек в улье без улучшений
CAP_STEP = 2
DISCOVERY_MULT = 3           # бонус за первую баночку нового вида мёда: 3 × цена
CYCLE_STEP = 0.07            # −7 % ко времени цикла за уровень матки
POLLEN_STEP = 0.08           # +8 % шанс лишней баночки за уровень пыльцы
JELLY_STEP = 0.02            # +2 % шанс баночки маточного молочка за уровень
M = 60

# цветы: id, название, значок, предмет со склада фермы (None — бесплатно), цикл (сек), мёд, циклов на одну штуку (0 — бесконечно)
_FLOWERS = [
    ("clover", "Луговые травы", "🌼", None, 40 * M, "clover", 0),
    ("sunflower", "Подсолнух", "🌻", "sunflower", 30 * M, "sunflower", 8),
    ("strawberry", "Клубника", "🍓", "strawberry", 50 * M, "berry", 8),
    ("pumpkin", "Тыква", "🎃", "pumpkin", 80 * M, "pumpkin", 6),
]
FLOWERS = {f[0]: {"id": f[0], "name": f[1], "icon": f[2], "item": f[3], "cycle": int(f[4] / SPEED), "honey": f[5], "lasts": f[6]} for f in _FLOWERS}

# мёд: id, название, значок, цена баночки (монет), ступень (0 — особый)
_HONEY = [
    ("clover", "Луговой мёд", "🍯", 18, 1), ("sunflower", "Подсолнуховый мёд", "🌻", 34, 2), ("berry", "Клубничный мёд", "🍓", 62, 3),
    ("pumpkin", "Тыквенный мёд", "🎃", 115, 4), ("jelly", "Маточное молочко", "👑", 420, 0),
]
HONEY = {h[0]: {"id": h[0], "name": h[1], "icon": h[2], "price": h[3], "tier": h[4]} for h in _HONEY}

UPGRADES = make_upgrades([
    ("hives", "Ульи", "🏠", "+1 улей (старт 2, максимум 8)", [800, 2400, 6000, 14000, 30000, 60000]),
    ("queen", "Матка", "👸", "−7 % ко времени цикла за уровень", [600, 1500, 3200, 7000, 15000]),
    ("frames", "Рамки", "🖼️", "+2 баночки помещаются в улей за уровень (старт 4)", [300, 700, 1500, 3200, 7000]),
    ("pollen", "Пыльца", "🌸", "+8 % шанс лишней баночки за уровень", [700, 1700, 3600, 8000, 17000]),
    ("jelly", "Молочко", "💧", "+2 % шанс маточного молочка (дорогая баночка) за уровень", [1500, 4000, 9000, 20000, 45000]),
    ("appraiser", "Оценщик", "⚖️", "+4 % к цене мёда за уровень", [1000, 2500, 6000, 13000, 28000]),
])


def hives_count(level: int) -> int:
    return START_HIVES + level


def cap_of(frames: int) -> int:
    return BASE_CAP + CAP_STEP * frames


def cycle_time(flower: str, queen: int) -> int:
    return max(1, int(FLOWERS[flower]["cycle"] * (1 - CYCLE_STEP * queen)))


def price_bonus(appraiser: int) -> float:
    return .04 * appraiser
