def shafts_count(level: int) -> int:
    return START_SHAFTS + level


def cart_cap(level: int) -> int:
    return BASE_CART + CART_STEP * level


def tier_open(tier: int, lift: int) -> bool:
    return tier <= lift + 1


def risk_of(tier: int, crib: int) -> float:
    return max(0.0, TIERS[tier]["risk"] - CRIB_STEP * crib)


def price_bonus(appraiser: int) -> float:
    return .04 * appraiser
