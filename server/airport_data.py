def rank_of(cancels: int) -> str:
    return [name for need, name in RANKS if cancels >= need][-1]


def next_rank(cancels: int):
    return next(((need, name) for need, name in RANKS if need > cancels), None)


def _h(*parts) -> int:
    return int(hashlib.sha256(":".join(str(p) for p in parts).encode()).hexdigest()[:12], 16)


def flight_no(seed) -> str:
    return f"{CODE}-{100 + _h('no', seed) % 900}"


def board(now: float, rows: int = 7) -> list:
    """Табло вылетов: одно на всех игроков, обновляется каждые 15 минут. Рейс из такой строки купить нельзя: он и так «по приколу»."""
    bucket = int(now // (15 * M / SPEED))
    out = []
    for i in range(rows):
        h = _h("board", bucket, i)
        w = h % 100
        status, acc = STATUS[0], 0
        for s in STATUS:
            acc += s[0]
            if w < acc:
                status = s
                break
        dest = DESTS[_h("d", bucket, i) % len(DESTS)]
        sched = (bucket + 1) * 15 * M / SPEED + (i + 1) * 17 * M / SPEED
        row = {"no": flight_no(f"{bucket}:{i}"), "dest": dest[0], "icon": dest[1], "sched": round(sched), "status": status[1], "status_text": status[2]}
        if status[1] == "cancel":
            row["reason"] = CANCEL[_h("r", bucket, i) % len(CANCEL)]
        elif status[1] in ("moved", "wait"):
            row["reason"] = DELAY[_h("r", bucket, i) % len(DELAY)]
            if status[1] == "moved":
                row["new_sched"] = round(sched + (2 + _h("m", bucket, i) % 8) * 3600 / SPEED)
        else:
            row["reason"] = "посадка идёт по расписанию, самолёт летит по своему"
        out.append(row)
    return out


def roll_trip(rng) -> dict:
    """Весь путь пассажира: что объявят и когда (секунды от покупки, уже с учётом SPEED), через сколько всё кончится и какая компенсация."""
    dest = rng.choice(DESTS)
    mid = rng.choice([d for d in DESTS if d != dest])[0]
    flight = flight_no(rng.random())
    steps = []

    def say(at: float, kind: str, icon: str, text: str):
        steps.append({"at": round(at / SPEED), "kind": kind, "icon": icon, "text": text, "flight": flight})

    def cancel(at: float):
        nonlocal flight
        reason = rng.choice(CANCEL)
        flight = flight_no(rng.random())
        say(at, "cancel", "❌", f"РЕЙС ОТМЕНЁН: {reason}. Вас пересадили на рейс {flight}, он вылетит «чуть позже»")

    say(0, "info", "🎫", f"Билет куплен: рейс {flight} в «{dest[0]}». Регистрация открыта, вылет по расписанию через 20 минут")
    t, cancels = 0.0, 0
    for _ in range(rng.randint(3, 5)):
        t += rng.randint(15, 40) * M
        if rng.random() < .55:
            cancels += 1
            cancel(t)
        else:
            hrs = rng.choice([1, 2, 3])
            say(t, "delay", "⏳", f"Рейс {flight} перенесён на {hrs} {'час' if hrs == 1 else 'часа'}: {rng.choice(DELAY)}")
    if not cancels:
        cancels = 1
        t += 10 * M
        cancel(t)
    t += 15 * M
    say(t, "board", "🚜", f"Посадка на рейс {flight} началась. До самолёта довезёт трактор, держитесь за ведро")
    for text in rng.sample(AIR, rng.randint(2, 3)):
        t += rng.randint(25, 45) * M
        say(t, "air", "💺", text.format(mid=mid))
    t += rng.randint(30, 50) * M
    say(t, "land", "🛬", rng.choice(LAND).format(dest=dest[0]))
    return {"dest": dest[0], "icon": dest[1], "flight": flight, "steps": steps, "total": steps[-1]["at"], "cancels": cancels, "reward": rng.randint(COMP_MIN, COMP_MAX),
            "comp_text": rng.choice(COMP)}
