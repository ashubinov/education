"""Данные локации «Озеро» (рыбалка рядом с фермой): рыбы, наживка, улучшения. Всё придумано для LearnQuest.

Удочки закидываются на наживку со склада фермы (пшеница, кукуруза, клубника): чем дороже наживка, тем дольше ждать клёва и тем ценнее рыба.
Улов определяется при подъёме удочки (на сервере), пока ты не смотришь, клёв идёт сам: время считается по меткам. Рыба продаётся за монеты фермы,
цены гуляют раз в сутки. Первая рыба нового вида даёт бонус открытия; собранная ступень «рыбного атласа» поднимает цены навсегда.
Для демонстрации и проверки время можно ускорить переменной окружения LAKE_SPEED (например, 120 — час превращается в полминуты).
"""
import os

try:
    SPEED = max(1.0, float(os.environ.get("LAKE_SPEED", "1")))
except ValueError:
    SPEED = 1.0

UNLOCK_FARM_LEVEL = 10
START_RODS = 2
BASE_KEEP = 20                # рыб в садке без улучшений
KEEP_STEP = 10
DISCOVERY_MULT = 3            # бонус за первую рыбу нового вида: 3 × её цена
TIER_BONUS = 0.03             # +3 % к цене рыбы за каждую полностью собранную ступень атласа
LEGEND_BASE = 0.01            # шанс легендарной рыбы за заброс при лодке 2+: 1 % + 1 % за уровень эхолота
CHEST_CHANCE, PEARL_CHANCE, JUNK_CHANCE = 0.01, 0.03, 0.06
CHEST_COINS = (300, 900)
DOUBLE_STEP = 0.07            # +7 % шанс двойного улова за уровень сети
REEL_STEP = 0.07              # −7 % ко времени клёва за уровень катушки
UP_TIER_CHANCE = 0.65         # шанс, что рыба из «своей» ступени наживки (иначе ступенью ниже)
M = 60

# наживка = предмет со склада фермы: id, время клёва (сек), ступень наживки
_BAITS = [("wheat", 20 * M, 1), ("corn", 45 * M, 2), ("strawberry", 90 * M, 3)]
BAITS = {b[0]: {"id": b[0], "time": int(b[1] / SPEED), "tier": b[2]} for b in _BAITS}

# рыба: id, название, значок, ступень, цена (монет). Ступень 0 — не рыба (хлам и жемчужина), 4 — легенды
_FISH = [
    ("crucian", "Карась", "🐟", 1, 12), ("roach", "Плотва", "🐟", 1, 16), ("perch", "Окунь", "🐠", 1, 22),
    ("bream", "Лещ", "🐟", 2, 40), ("pike", "Щука", "🐊", 2, 58), ("zander", "Судак", "🐠", 2, 80),
    ("trout", "Форель", "🐟", 3, 150), ("sturgeon", "Осётр", "🦈", 3, 260), ("salmon", "Лосось", "🍣", 3, 380),
    ("goldfish", "Золотая рыбка", "🐡", 4, 1500), ("koi", "Радужный кои", "🎏", 4, 2400), ("moonfish", "Лунный сом", "🌙", 4, 4000),
    ("boot", "Старый сапог", "🥾", 0, 2), ("pearl", "Жемчужина", "🦪", 0, 260),
]
FISH = {f[0]: {"id": f[0], "name": f[1], "icon": f[2], "tier": f[3], "price": f[4]} for f in _FISH}
TIERS = {t: [k for k, v in FISH.items() if v["tier"] == t] for t in (1, 2, 3, 4)}
TIER_NAMES = {1: "Пруд", 2: "Река", 3: "Глубина", 4: "Легенды"}

# улучшения: ключ → название, значок, описание эффекта на уровень, цены по уровням (монет)
_UPGRADES = [
    ("rods", "Удилища", "🎣", "+1 удочка (старт 2, максимум 6)", [800, 2500, 6000, 14000]),
    ("reel", "Катушка", "⚙️", "−7 % ко времени клёва за уровень", [500, 1200, 2600, 5500, 12000]),
    ("boat", "Лодка", "⛵", "уровень 1 открывает глубины (ступень 3), уровень 2 — легендарную рыбу", [3000, 12000]),
    ("net", "Сеть", "🕸️", "+7 % шанс двойного улова за уровень", [600, 1500, 3200, 7000, 15000]),
    ("sonar", "Эхолот", "📡", "+1 % шанс легендарной рыбы за уровень (нужна лодка 2)", [2500, 6000, 13000, 28000, 60000]),
    ("keep", "Садок", "🧺", "+10 мест для рыбы за уровень (старт 20)", [300, 700, 1500, 3000, 6500]),
    ("appraiser", "Оценщик", "⚖️", "+4 % к цене рыбы за уровень", [1000, 2500, 6000, 13000, 28000]),
]
UPGRADES = {u[0]: {"key": u[0], "name": u[1], "icon": u[2], "desc": u[3], "costs": u[4], "max": len(u[4])} for u in _UPGRADES}


def rods_count(level: int) -> int:
    return START_RODS + level


def keep_cap(level: int) -> int:
    return BASE_KEEP + KEEP_STEP * level


def bite_time(bait: str, reel: int) -> int:
    return max(1, int(BAITS[bait]["time"] * (1 - REEL_STEP * reel)))


def legend_chance(boat: int, sonar: int) -> float:
    return LEGEND_BASE * (1 + sonar) if boat >= 2 else 0.0


def price_bonus(appraiser: int, tiers_done: int) -> float:
    return .04 * appraiser + TIER_BONUS * tiers_done


def max_tier(boat: int) -> int:
    """Наибольшая ступень обычной рыбы: без лодки — река, с лодкой — глубина."""
    return 3 if boat >= 1 else 2
